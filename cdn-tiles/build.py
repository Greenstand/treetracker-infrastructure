"""Write robots-function.js (a CloudFront Function) from robots.txt.

Usage: python3 build.py          write robots-function.js
       python3 build.py --check  exit 1 if robots-function.js is not current
The files are read and written as bytes, so the served body is byte-equal to robots.txt.
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SIZE_LIMIT = 10240  # bytes, the CloudFront Functions limit for the function code
TEMPLATE = """\
// CloudFront Function (cloudfront-js-2.0), event type viewer-request, cache behavior /robots.txt.
// It returns robots.txt at the edge: the request does not go to the cache or to the origin.
// Generated by build.py from robots.txt. Do not edit: change robots.txt, then run python3 build.py.
var BODY = __BODY__;

function handler(event) {
    return {
        statusCode: 200,
        statusDescription: 'OK',
        headers: {
            'content-type': { value: 'text/plain; charset=utf-8' },
            'cache-control': { value: 'public, max-age=3600' }
        },
        body: { encoding: 'text', data: BODY }
    };
}
"""


def read(path):
    return path.read_bytes().decode("utf-8")


def render(robots):
    return TEMPLATE.replace("__BODY__", json.dumps(robots))


def main():
    parser = argparse.ArgumentParser(description="Write robots-function.js from robots.txt.")
    parser.add_argument("--check", action="store_true", help="exit 1 if robots-function.js is not current")
    args = parser.parse_args()
    code = render(read(HERE / "robots.txt"))
    if len(code.encode("utf-8")) > SIZE_LIMIT:
        sys.exit(f"robots-function.js is larger than {SIZE_LIMIT} bytes")
    target = HERE / "robots-function.js"
    if args.check:
        if not target.exists() or read(target) != code:
            sys.exit("robots-function.js is not current: run python3 build.py")
        return
    target.write_bytes(code.encode("utf-8"))


if __name__ == "__main__":
    main()
